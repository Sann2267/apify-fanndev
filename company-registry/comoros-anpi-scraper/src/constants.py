"""Endpoints, headers, and recon summary -- all in one place.

Recon summary (2026-08-27): Comoros has no dedicated "Guichet Unique"/RCCM
portal of its own online (the OHADA-wide RCCM system does not list Comoros
as a member state -- Comoros is not an OHADA party). The de-facto official
company/business registry with an online, public search is run by the
**ANPI (Agence Nationale pour la Promotion des Investissements)**, the
government agency that also operates the country's single-window business
registration desk. Its site, `investcomoros.net`, publishes an "Annuaire
des entreprises" (business directory) page backed by a small custom WordPress
plugin (`anpi-annonces`) that exposes a clean, public, unauthenticated JSON
REST endpoint -- this is what this actor scrapes.

`robots.txt` (`https://www.investcomoros.net/robots.txt`) is the stock
HestiaCP-autogenerated file:

    # hestiacp autogenerated robots.txt
    User-agent: *
    Crawl-delay: 10

One `User-agent: *` group, no `Disallow` line at all, no mention of
Claude/ClaudeBot/anthropic-ai/GPTBot/AI crawlers anywhere in the literal
text. `Crawl-delay: 10` is honored by this actor's low default concurrency
and by not hammering pagination beyond what's needed.

## The API: a plain WordPress REST route, no login, no nonce required for GET

The directory page (`/annuaire-des-entreprises/`) is an Elementor/WordPress
page whose search widget is a small vanilla-JS frontend
(`wp-content/plugins/anpi-annonces/assets/js/frontend.js`) that fetches from
a REST route registered by the same plugin:

    GET https://www.investcomoros.net/wp-json/anpi/v1/annonces
        ?search=<free text on nom>
        &ile=<grande_comore|anjouan|moheli>
        &secteur=<sector code>
        &annee=<year>
        &rccm=<RCCM number>
        &siege=<headquarters/city text>
        &orderby=<nom|annee>&order=<ASC|DESC>
        &page=<1-based>&per_page=<n>

The page embeds `ANPI_CONFIG = {"rest_url": ..., "nonce": "..."}` and the JS
sends the nonce as an `X-WP-Nonce` header on every request, but this was
confirmed **NOT required** -- a bare `curl_cffi` GET with no nonce header at
all and no cookies returns the identical 200 JSON payload. The route's
`permission_callback` is evidently public (`__return_true` or equivalent);
the nonce is only there to support the WordPress admin bar's "logged in"
convenience, not as an access gate.

Response shape: `{"total": <int>, "pages": <int>, "data": [<row>, ...]}`.
Each row: `id, nom, rccm, ile, secteur, annee, siege, ville, dirigeant,
capital, forme_juridique, description, date_creation, date_maj`.

Confirmed during recon (2026-08-27, `curl_cffi` `chrome124`, no proxy):
- `per_page` is server-capped at **200** -- requesting `per_page=500` still
  returns 200 rows/page (verified: `pages` recalculates against the 200 cap,
  not the requested value). This actor never requests more than 200.
- Filters combine with AND semantics and all confirmed working server-side:
  `ile=anjouan` -> 1194/6376; `ile=moheli` -> 452; `ile=grande_comore` ->
  4725; `annee=2024` -> 581; `siege=Moroni` (substring) -> 2696;
  `search=SARL` -> 2786.
- An out-of-range `page` (e.g. 9999) returns HTTP 200 with `data: []`, not
  an error -- a clean, safe pagination-end signal.
- No WAF/CAPTCHA/challenge markers observed on any request (plain `nginx`
  reverse proxy in front of a HestiaCP-hosted WordPress install).

## Known upstream data-quality quirk (not a scraping bug)

Sampling **all 6376 records** (every page at `per_page=200`) during recon
found `rccm`, `dirigeant`, `capital`, `secteur`, and `ville` are **empty
string on every single row in the entire directory**, with zero exceptions.
Only `nom`, `ile`, `annee`, `siege`, `forme_juridique`, `date_creation`, and
`date_maj` are ever populated. Consequently the `secteur`/`rccm` search
filters exposed by ANPI's own UI currently never actually narrow anything
(e.g. `secteur=commerce` -> 0 results, even though "Commerce & distribution"
is listed as a selectable sector in the UI). This actor still passes these
filters through to the API (in case ANPI populates them later) and does
raw passthrough of whatever the API returns, per this portfolio's principle
of not fabricating data upstream doesn't have -- but this is documented here
and in the README so a run returning empty `rccm`/`secteur`/`capital`/
`dirigeant`/`ville` fields is *expected*, not a bug in this actor.

## No per-entity detail endpoint

`GET /wp-json/anpi/v1/annonces/<id>` returns HTTP 404
(`{"code":"rest_no_route", ...}`) -- there is no separate detail route.
The list endpoint already returns every field the plugin knows about per
row, so there is nothing more to fetch per match.
"""

